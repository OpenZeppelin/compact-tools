//! Text emission and layout.
//!
//! Groups are separated by one blank line. The import block has four groups: the
//! standard library, interfaces, named imports, module imports. An import or export
//! list, and a call statement, stay on one line up to [`MAX_WIDTH`] characters and break
//! one item per line above it. Signatures and prefixed imports never break.

use crate::plan::{Call, Constructor, ImportLine, MockPlan, Param, Wrapper};

/// The header line, after the SPDX line when there is one. Stale removal and overwrites
/// check it beside the stamp.
pub const MARKER: &str = "// Generated by compact-mock";

/// The SPDX line's opening.
pub const SPDX_PREFIX: &str = "// SPDX-License-Identifier: ";

const NOT_FOR_PRODUCTION: &str =
    "// FOR TESTING PURPOSES ONLY. DO NOT deploy or use this contract in production.";

/// Widest single-line list or call, in Unicode scalar values.
pub const MAX_WIDTH: usize = 80;

const INDENT: &str = "  ";

/// The complete file text, ending in exactly one newline.
#[must_use]
pub fn render(plan: &MockPlan) -> String {
    let mut groups: Vec<String> = Vec::new();

    let mut header = Vec::new();
    if let Some(spdx) = &plan.spdx {
        header.push(format!("{SPDX_PREFIX}{spdx}"));
    }
    header.push(format!(
        "{MARKER} from {}. Do not edit by hand.",
        plan.module
    ));
    header.push(NOT_FOR_PRODUCTION.to_owned());
    groups.push(header.join("\n"));

    groups.push(plan.pragma.clone());
    groups.push("import CompactStandardLibrary;".to_owned());

    for imports in [&plan.interfaces, &plan.named, &plan.prefixed] {
        if !imports.is_empty() {
            groups.push(
                imports
                    .iter()
                    .map(import_line)
                    .collect::<Vec<_>>()
                    .join("\n"),
            );
        }
    }
    if !plan.implements.is_empty() {
        groups.push(
            plan.implements
                .iter()
                .map(|name| format!("contract implements {name};"))
                .collect::<Vec<_>>()
                .join("\n"),
        );
    }
    if !plan.exports.is_empty() {
        groups.push(list("export {", &plan.exports, "};"));
    }
    if plan.guard_ledger {
        groups.push("ledger _invocations: Counter;".to_owned());
    }
    if let Some(constructor) = &plan.constructor {
        groups.push(constructor_text(constructor));
    }
    for wrapper in &plan.wrappers {
        groups.push(wrapper_text(wrapper));
    }
    if let Some(include) = &plan.include {
        groups.push(format!("include \"{include}\";"));
    }

    let mut text = groups.join("\n\n");
    text.push('\n');
    text
}

fn import_line(line: &ImportLine) -> String {
    match line {
        ImportLine::Selective { names, path, args } => {
            list("import {", names, &format!("}} from \"{path}\"{args};"))
        }
        ImportLine::Prefixed { path, args, prefix } => {
            format!("import \"{path}\"{args} prefix {prefix};")
        }
        ImportLine::Whole { path, args } => format!("import \"{path}\"{args};"),
    }
}

/// `open a, b close` on one line when it fits, else one item per line.
fn list(open: &str, items: &[String], close: &str) -> String {
    let single = format!("{open} {} {close}", items.join(", "));
    if width(&single) <= MAX_WIDTH {
        return single;
    }
    let mut lines = vec![open.to_owned()];
    let last = items.len().saturating_sub(1);
    for (index, item) in items.iter().enumerate() {
        let comma = if index == last { "" } else { "," };
        lines.push(format!("{INDENT}{item}{comma}"));
    }
    lines.push(close.to_owned());
    lines.join("\n")
}

fn width(line: &str) -> usize {
    line.chars().count()
}

fn params_text(params: &[Param]) -> String {
    params
        .iter()
        .map(|param| format!("{}: {}", param.name, param.ty))
        .collect::<Vec<_>>()
        .join(", ")
}

fn constructor_text(constructor: &Constructor) -> String {
    let mut params: Vec<Param> = constructor.params.clone();
    for flag in &constructor.flags {
        params.push(Param {
            name: flag.clone(),
            ty: "Boolean".to_owned(),
        });
    }
    let params = params_text(&params);
    let mut lines = vec![format!("constructor({params}) {{")];
    for (flag, call) in &constructor.calls {
        match flag {
            Some(flag) => {
                lines.push(format!("{INDENT}if (disclose({flag})) {{"));
                lines.push(call_statement(&format!("{INDENT}{INDENT}"), "", call, ""));
                lines.push(format!("{INDENT}}}"));
            }
            None => lines.push(call_statement(INDENT, "", call, "")),
        }
    }
    lines.push("}".to_owned());
    lines.join("\n")
}

fn wrapper_text(wrapper: &Wrapper) -> String {
    let pure = if wrapper.pure { "pure " } else { "" };
    let mut lines = vec![format!(
        "export {pure}circuit {}({}): {} {{",
        wrapper.name,
        params_text(&wrapper.params),
        wrapper.ret
    )];
    if wrapper.guard {
        lines.push(format!("{INDENT}_invocations.increment(1);"));
    }
    let (lead, tail) = if wrapper.disclose {
        ("return disclose(", ")")
    } else {
        ("return ", "")
    };
    lines.push(call_statement(INDENT, lead, &wrapper.call, tail));
    lines.push("}".to_owned());
    lines.join("\n")
}

/// `<indent><lead><callee>(<args>)<tail>;`, one argument per line when it does not fit.
fn call_statement(indent: &str, lead: &str, call: &Call, tail: &str) -> String {
    let single = format!(
        "{indent}{lead}{}({}){tail};",
        call.callee,
        call.args.join(", ")
    );
    if width(&single) <= MAX_WIDTH || call.args.is_empty() {
        return single;
    }
    let mut lines = vec![format!("{indent}{lead}{}(", call.callee)];
    let last = call.args.len() - 1;
    for (index, arg) in call.args.iter().enumerate() {
        let comma = if index == last { "" } else { "," };
        lines.push(format!("{indent}{INDENT}{arg}{comma}"));
    }
    lines.push(format!("{indent}){tail};"));
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    use super::{
        MARKER, call_statement, constructor_text, import_line, list, render, wrapper_text,
    };
    use crate::plan::{Call, Constructor, ImportLine, MockPlan, Param, Wrapper};

    fn items(widths: &[usize]) -> Vec<String> {
        widths.iter().map(|width| "x".repeat(*width)).collect()
    }

    #[test]
    fn a_list_of_exactly_eighty_columns_stays_on_one_line() {
        // "export { " + 33 + ", " + 33 + " };"
        let line = list("export {", &items(&[33, 33]), "};");
        assert_eq!(line.chars().count(), 80);
        assert!(!line.contains('\n'));
    }

    #[test]
    fn a_list_of_eighty_one_columns_wraps_one_item_per_line() {
        let wide = items(&[33, 34]);
        assert_eq!(
            list("export {", &wide, "};"),
            format!("export {{\n  {},\n  {}\n}};", wide[0], wide[1])
        );
    }

    #[test]
    fn width_counts_characters_not_bytes() {
        let item = "é".repeat(68);
        assert_eq!(item.len(), 136);
        let line = list("export {", &[item], "};");
        assert!(!line.contains('\n'));
    }

    #[test]
    fn a_long_call_breaks_one_argument_per_line() {
        let call = Call {
            callee: "Module_transfer".to_owned(),
            args: vec![
                "A_authenticate(pad(32, \"MockModuleWithALongName\"))".to_owned(),
                "to".to_owned(),
            ],
        };
        assert_eq!(
            call_statement("  ", "return ", &call, ""),
            "  return Module_transfer(\n    A_authenticate(pad(32, \"MockModuleWithALongName\")),\n    to\n  );"
        );
        assert_eq!(
            call_statement("  ", "return disclose(", &call, ")"),
            "  return disclose(Module_transfer(\n    A_authenticate(pad(32, \"MockModuleWithALongName\")),\n    to\n  ));"
        );
    }

    #[test]
    fn a_call_of_eighty_columns_stays_on_one_line() {
        let call = Call {
            callee: "f".to_owned(),
            args: vec!["a".repeat(67)],
        };
        let line = call_statement("  ", "return ", &call, "");
        assert_eq!(line.chars().count(), 80);
        let longer = Call {
            callee: "f".to_owned(),
            args: vec!["a".repeat(68)],
        };
        assert!(call_statement("  ", "return ", &longer, "").contains('\n'));
    }

    fn plan() -> MockPlan {
        MockPlan {
            name: "MockM".to_owned(),
            path: "/x/MockM.compact".into(),
            module: "a/M".to_owned(),
            artifacts: "/x".into(),
            spdx: None,
            pragma: "pragma language_version >= 0.28.0;".to_owned(),
            interfaces: Vec::new(),
            named: Vec::new(),
            prefixed: Vec::new(),
            implements: Vec::new(),
            exports: Vec::new(),
            guard_ledger: true,
            constructor: Some(Constructor {
                params: Vec::new(),
                flags: vec!["isInit".to_owned()],
                calls: vec![(
                    Some("isInit".to_owned()),
                    Call {
                        callee: "M_initialize".to_owned(),
                        args: Vec::new(),
                    },
                )],
            }),
            wrappers: vec![Wrapper {
                name: "hash".to_owned(),
                pure: false,
                params: vec![Param {
                    name: "v".to_owned(),
                    ty: "Field".to_owned(),
                }],
                ret: "Field".to_owned(),
                guard: true,
                injected: 0,
                disclose: true,
                call: Call {
                    callee: "M_hash".to_owned(),
                    args: vec!["v".to_owned()],
                },
            }],
            include: Some("MockM.fragment".to_owned()),
            covered: std::collections::BTreeSet::new(),
        }
    }

    #[test]
    fn groups_are_separated_by_one_blank_line() {
        assert_eq!(
            render(&plan()),
            format!(
                "{MARKER} from a/M. Do not edit by hand.\n\
                 // FOR TESTING PURPOSES ONLY. DO NOT deploy or use this contract in production.\n\
                 \n\
                 pragma language_version >= 0.28.0;\n\
                 \n\
                 import CompactStandardLibrary;\n\
                 \n\
                 ledger _invocations: Counter;\n\
                 \n\
                 constructor(isInit: Boolean) {{\n\
                 \x20 if (disclose(isInit)) {{\n\
                 \x20   M_initialize();\n\
                 \x20 }}\n\
                 }}\n\
                 \n\
                 export circuit hash(v: Field): Field {{\n\
                 \x20 _invocations.increment(1);\n\
                 \x20 return disclose(M_hash(v));\n\
                 }}\n\
                 \n\
                 include \"MockM.fragment\";\n"
            )
        );
    }

    #[test]
    fn the_marker_follows_the_spdx_line() {
        let mut with_spdx = plan();
        with_spdx.spdx = Some("MIT".to_owned());
        let text = render(&with_spdx);
        let mut lines = text.lines();
        assert_eq!(lines.next(), Some("// SPDX-License-Identifier: MIT"));
        assert!(lines.next().is_some_and(|line| line.starts_with(MARKER)));
        assert_eq!(
            lines.next(),
            Some("// FOR TESTING PURPOSES ONLY. DO NOT deploy or use this contract in production.")
        );
    }

    #[test]
    fn the_marker_text_is_stable() {
        assert_eq!(MARKER, "// Generated by compact-mock");
    }

    fn param(name: &str, ty: &str) -> Param {
        Param {
            name: name.to_owned(),
            ty: ty.to_owned(),
        }
    }

    #[test]
    fn a_plain_constructor_forwards_its_parameters_in_order() {
        let constructor = Constructor {
            params: vec![param("owner", "Bytes<32>"), param("cap", "Uint<64>")],
            flags: Vec::new(),
            calls: vec![(
                None,
                Call {
                    callee: "M_initialize<3>".to_owned(),
                    args: vec!["owner".to_owned(), "cap".to_owned()],
                },
            )],
        };
        assert_eq!(
            constructor_text(&constructor),
            "constructor(owner: Bytes<32>, cap: Uint<64>) {\n  M_initialize<3>(owner, cap);\n}"
        );
    }

    #[test]
    fn a_flag_constructor_breaks_its_call_at_the_inner_indentation() {
        let constructor = Constructor {
            params: Vec::new(),
            flags: vec!["ready".to_owned()],
            calls: vec![(
                Some("ready".to_owned()),
                Call {
                    callee: "Module_initialize".to_owned(),
                    args: vec![format!(
                        "Auth_authenticate(pad(32, \"{}\"))",
                        "a".repeat(32)
                    )],
                },
            )],
        };
        assert_eq!(
            constructor_text(&constructor),
            format!(
                "constructor(ready: Boolean) {{\n  if (disclose(ready)) {{\n    Module_initialize(\n      Auth_authenticate(pad(32, \"{}\"))\n    );\n  }}\n}}",
                "a".repeat(32)
            )
        );
    }

    #[test]
    fn signatures_and_prefixed_imports_never_wrap() {
        let wrapper = Wrapper {
            name: "transfer".to_owned(),
            pure: true,
            params: vec![
                param("recipient", "Either<ZswapCoinPublicKey, ContractAddress>"),
                param("amount", "Uint<128>"),
            ],
            ret: "Either<ZswapCoinPublicKey, ContractAddress>".to_owned(),
            guard: false,
            injected: 0,
            disclose: false,
            call: Call {
                callee: "T_transfer".to_owned(),
                args: vec!["recipient".to_owned(), "amount".to_owned()],
            },
        };
        let text = wrapper_text(&wrapper);
        let signature = text.lines().next().expect("a signature");
        assert!(signature.starts_with("export pure circuit transfer("));
        assert!(signature.chars().count() > 80 && signature.ends_with(" {"));
        let prefixed = ImportLine::Prefixed {
            path: format!("../../{}/Module", "deep/".repeat(12)),
            args: "<Bytes<32>, Uint<64>>".to_owned(),
            prefix: "Module_".to_owned(),
        };
        assert!(!import_line(&prefixed).contains('\n'));
        let whole = ImportLine::Whole {
            path: "../../Who".to_owned(),
            args: String::new(),
        };
        assert_eq!(import_line(&whole), "import \"../../Who\";");
    }

    #[test]
    fn a_selective_import_wraps_one_name_per_line_past_eighty_columns() {
        let short = ImportLine::Selective {
            names: vec!["a".to_owned(), "b".to_owned()],
            path: "../../M".to_owned(),
            args: "<1>".to_owned(),
        };
        assert_eq!(import_line(&short), "import { a, b } from \"../../M\"<1>;");
        let long = ImportLine::Selective {
            names: vec!["x".repeat(30), "y".repeat(30)],
            path: "../../M".to_owned(),
            args: String::new(),
        };
        assert_eq!(
            import_line(&long),
            format!(
                "import {{\n  {},\n  {}\n}} from \"../../M\";",
                "x".repeat(30),
                "y".repeat(30)
            )
        );
    }

    #[test]
    fn a_merged_constructor_shares_parameters_then_takes_each_flag() {
        let call = |callee: &str| Call {
            callee: callee.to_owned(),
            args: vec!["salt".to_owned(), "signers".to_owned()],
        };
        let constructor = Constructor {
            params: vec![
                param("salt", "Bytes<32>"),
                param("signers", "Vector<3, Bytes<32>>"),
            ],
            flags: vec!["initializeThree".to_owned()],
            calls: vec![
                (None, call("Two_initialize<3>")),
                (
                    Some("initializeThree".to_owned()),
                    call("Three_initialize<3>"),
                ),
            ],
        };
        assert_eq!(
            constructor_text(&constructor),
            "constructor(salt: Bytes<32>, signers: Vector<3, Bytes<32>>, initializeThree: Boolean) {\n  \
             Two_initialize<3>(salt, signers);\n  if (disclose(initializeThree)) {\n    \
             Three_initialize<3>(salt, signers);\n  }\n}"
        );
    }

    #[test]
    fn the_four_import_groups_and_implements_lines_are_separated_by_blank_lines() {
        let mut grouped = plan();
        grouped.guard_ledger = false;
        grouped.constructor = None;
        grouped.wrappers.clear();
        grouped.include = None;
        grouped.interfaces = vec![ImportLine::Selective {
            names: vec!["Tally".to_owned()],
            path: "../../Iface".to_owned(),
            args: String::new(),
        }];
        grouped.named = vec![ImportLine::Selective {
            names: vec!["get".to_owned()],
            path: "../../M".to_owned(),
            args: String::new(),
        }];
        grouped.prefixed = vec![ImportLine::Prefixed {
            path: "../../M".to_owned(),
            args: String::new(),
            prefix: "M_".to_owned(),
        }];
        grouped.implements = vec!["Tally".to_owned()];
        let text = render(&grouped);
        assert!(
            text.ends_with(
                "import CompactStandardLibrary;\n\n\
             import { Tally } from \"../../Iface\";\n\n\
             import { get } from \"../../M\";\n\n\
             import \"../../M\" prefix M_;\n\n\
             contract implements Tally;\n"
            ),
            "{text}"
        );
    }

    #[test]
    fn a_call_without_arguments_never_breaks() {
        let call = Call {
            callee: format!("Module_{}", "c".repeat(90)),
            args: Vec::new(),
        };
        assert!(!call_statement("  ", "return ", &call, "").contains('\n'));
    }

    #[test]
    fn empty_groups_are_left_out_and_the_file_ends_in_one_newline() {
        let mut bare = plan();
        bare.guard_ledger = false;
        bare.constructor = None;
        bare.wrappers.clear();
        bare.include = None;
        let text = render(&bare);
        assert!(!text.contains("export {"));
        assert!(!text.contains("_invocations"));
        assert!(text.ends_with("import CompactStandardLibrary;\n"));
        assert!(!text.ends_with("\n\n"));
    }

    #[test]
    fn a_pure_wrapper_is_rendered_pure_and_unguarded() {
        let mut pure = plan();
        pure.wrappers[0].pure = true;
        pure.wrappers[0].guard = false;
        let text = render(&pure);
        assert!(text.contains(
            "export pure circuit hash(v: Field): Field {\n  return disclose(M_hash(v));\n}"
        ));
    }
}
